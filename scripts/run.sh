#!/bin/bash
set -e

if [ "$EUID" -ne 0 ]; then
  echo "Error: please run as root!"
  exit 1
fi

if [[ ! ( -f "$SNAP_USER_DATA/internal.firewall-control-connected" && -f "$SNAP_USER_DATA/internal.network-control-connected" ) ]]; then
    echo "Error: please connect interfaces"
    sleep infinity
fi

for var in "$@"
do
    if [[ "$found" == true ]]; then
        CONFIG_FILE="$var"
        # echo "true $CONFIG_FILE"
        break
    fi
    if [[ "$var" == "--config" ]]; then
        found=true
    fi
done

if [[ ! -f "$CONFIG_FILE" ]]; then
    echo "Error: please generate config"
    sleep infinity
fi    

# Values the CLI (cli.py) wrote for this daemon: TUNNEL_NETWORK,
# TUNNEL_NETWORK_6, DNS_SERVERS (the nameservers pushed to clients) and
# CLIENT_TO_CLIENT. Only root can write this file.
ENV_FILE="${CONFIG_FILE%.conf}.env"
if [[ ! -f "$ENV_FILE" ]]; then
    echo "Error: please generate config"
    sleep infinity
fi
# shellcheck source=/dev/null
source "$ENV_FILE"
echo "tunnel networks: ${TUNNEL_NETWORK} ${TUNNEL_NETWORK_6}"
echo "dns servers: ${DNS_SERVERS[*]}"
echo "client-to-client: ${CLIENT_TO_CLIENT}"

# Stage packages don't get the `iptables` command that update-alternatives
# normally sets up, so call the nft backend directly (core22's base also used it).
IPTABLES=iptables-nft
IP6TABLES=ip6tables-nft

COMMENT="generated by easy-openvpn-server"
# One chain per daemon, e.g. `eovpn-udp-server`, for the traffic its clients send through the server.
CHAIN="eovpn-$(basename "$CONFIG_FILE" .conf)"

# Destinations VPN clients must never reach: cloud metadata services. They
# hand out the server's cloud credentials to anyone who can reach them from
# the server, and VPN traffic is NATed behind the server.
BLOCKED_V4=(
    169.254.0.0/16      # link-local, incl. the metadata service of most clouds (169.254.169.254)
    168.63.129.16/32    # Azure WireServer
    100.100.100.200/32  # Alibaba Cloud metadata
)
BLOCKED_V6=(
    fd00:ec2::254/128   # AWS metadata over IPv6
    fd20:ce::254/128    # GCP metadata over IPv6
)

# remove_rule <$IPTABLES|$IP6TABLES> <args>: delete every copy of a rule, so
# leftovers from a crash don't pile up.
remove_rule() {
    local cmd="$1"
    shift
    while "$cmd" "${@/#-A/-D}" -m comment --comment "$COMMENT" 2>/dev/null; do :; done
    if "$cmd" "${@/#-A/-C}" -m comment --comment "$COMMENT" 2>/dev/null; then
        echo "Error: failed to remove firewall rule: $cmd $*" >&2
    fi
}

add_rule() {
    local cmd="$1"
    shift
    remove_rule "$cmd" "$@"
    "$cmd" "$@" -m comment --comment "$COMMENT"
}

# setup_chain <$IPTABLES|$IP6TABLES> <tunnel network> <blocked destinations...>
setup_chain() {
    local cmd="$1" net="$2" dns dest family
    shift 2
    "$cmd" -N "$CHAIN" 2>/dev/null || "$cmd" -F "$CHAIN"
    # Some clouds run their DNS resolver on a metadata address (e.g. GCP's
    # 169.254.169.254), and we push the server's resolvers to clients.
    family=4
    [[ "$cmd" == "$IP6TABLES" ]] && family=6
    for dns in "${DNS_SERVERS[@]}"
    do
        if [[ ( "$family" == 6 && "$dns" == *:* ) || ( "$family" == 4 && "$dns" != *:* ) ]]
        then
            "$cmd" -A "$CHAIN" -d "$dns" -p udp --dport 53 -j RETURN
            "$cmd" -A "$CHAIN" -d "$dns" -p tcp --dport 53 -j RETURN
        fi
    done
    for dest in "$@"
    do
        "$cmd" -A "$CHAIN" -d "$dest" -j REJECT
    done
    # Traffic to other VPN clients, of this server or the other one.
    if [[ "$CLIENT_TO_CLIENT" == block ]]
    then
        "$cmd" -A "$CHAIN" -o tun+ -j REJECT
    fi
    remove_rule "$cmd" -A FORWARD -s "$net" -j "$CHAIN"
    "$cmd" -I FORWARD -s "$net" -j "$CHAIN" -m comment --comment "$COMMENT"
}

remove_chain() {
    local cmd="$1" net="$2"
    remove_rule "$cmd" -A FORWARD -s "$net" -j "$CHAIN"
    "$cmd" -F "$CHAIN" 2>/dev/null || true
    "$cmd" -X "$CHAIN" 2>/dev/null || true
}

function cleanup {
  echo Cleaning up...
  #sysctl -w net.ipv4.ip_forward=${ORIG_FORWARD_VALUE}
  remove_rule "$IPTABLES" -t nat -A POSTROUTING -s "$TUNNEL_NETWORK" -j MASQUERADE
  remove_rule "$IP6TABLES" -t nat -A POSTROUTING -s "$TUNNEL_NETWORK_6" -j MASQUERADE
  remove_chain "$IPTABLES" "$TUNNEL_NETWORK"
  remove_chain "$IP6TABLES" "$TUNNEL_NETWORK_6"
}
# Set the trap before adding any rules, so a stop during startup doesn't
# leave rules behind. Exit on SIGTERM so the EXIT trap always runs.
trap cleanup EXIT
trap 'exit 143' TERM INT

add_rule "$IPTABLES" -t nat -A POSTROUTING -s "$TUNNEL_NETWORK" -j MASQUERADE
# Note: see ipv6.md for more info on why we're using MASQUERADE NAT.
add_rule "$IP6TABLES" -t nat -A POSTROUTING -s "$TUNNEL_NETWORK_6" -j MASQUERADE
setup_chain "$IPTABLES" "$TUNNEL_NETWORK" "${BLOCKED_V4[@]}"
setup_chain "$IP6TABLES" "$TUNNEL_NETWORK_6" "${BLOCKED_V6[@]}"

ORIG_FORWARD_VALUE=$(sysctl net.ipv4.ip_forward -b)
sysctl -w net.ipv4.ip_forward=1
sysctl -w net.ipv6.conf.all.forwarding=1
# https://strugglers.net/~andy/blog/2011/09/04/linux-ipv6-router-advertisements-and-forwarding/
sysctl -w net.ipv6.conf.all.accept_ra=2

# Execute normally instead of with exec so our trap works correctly.
"$@"
